// Writes build/assets.generated.ts for build/compile-entry.ts: one `with { type: "file" }` import per on-disk asset tobor
// reads at runtime (package.json, init skeleton, artifact themes, vendored Tailwind), so the compiled binary embeds them.
// New files under these globs need no registration. `bun run build` runs this (`bun run gen:assets`) first.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const GLOBS = ["package.json", "src/server/skeleton/**/*.{md,yml,json}", "src/artifacts/themes/**", "src/artifacts/vendor/**"];

const root = join(import.meta.dirname, "..");
const found = new Set<string>();
for (const pattern of GLOBS) for (const path of new Bun.Glob(pattern).scanSync({ cwd: root, onlyFiles: true })) found.add(path);
const files = [...found].sort();

const hash = createHash("sha256");
for (const path of files) hash.update(path).update("\0").update(readFileSync(join(root, path))).update("\0");
const id = hash.digest("hex").slice(0, 16);

const lines = [
	"// Generated by build/gen-assets.ts (`bun run gen:assets`); do not edit.",
	...files.map((path, i) => `import a${i} from ${JSON.stringify(`../${path}`)} with { type: "file" };`),
	"",
	"/** Content hash of every asset: the extraction dir name under `$XDG_CACHE_HOME/tobor/assets/`. */",
	`export const ASSETS_HASH = ${JSON.stringify(id)};`,
	"",
	"/** Repo-relative path → embedded `/$bunfs` path. */",
	"export const ASSETS: Record<string, string> = {",
	...files.map((path, i) => `\t${JSON.stringify(path)}: a${i},`),
	"};",
	"",
];
writeFileSync(join(import.meta.dirname, "assets.generated.ts"), lines.join("\n"));
console.log(`build/assets.generated.ts: ${files.length} assets, ${id}`);
